#!/usr/bin/env python3
"""Copy PX4's x500 Gazebo model with the propeller collisions removed (``x500_course``).

Why: PX4's x500 has collision boxes on its spinning propellers that reach 0.31 m from the centre,
so its footprint is about 0.63 m square, larger than our 0.40 x 0.50 m drone.  On the course its
blades would clip walls our drone clears.  This copy keeps everything else (body collision,
inertia, motors, sensors), so PX4's x500 airframe flies it unchanged; clearance for the real drone
is judged afterwards by 16_analyze_flight.py, not by Gazebo contacts.

Writes ``x500_course_base``, ``x500_course`` and ``x500_course_lidar_2d`` into --out (default
course/gazebo/models, git-ignored because they are derived from the PX4 checkout).  Standard
library only; run_sitl.sh calls it.

    python3 course/gazebo/make_sim_drone.py --px4 ~/PX4-Autopilot
"""

from __future__ import annotations

import argparse
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent


def _write(folder: Path, name: str, root: ET.Element, source: str) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    ET.indent(root, space="  ")
    (folder / "model.sdf").write_text('<?xml version="1.0"?>\n' + ET.tostring(root, encoding="unicode") + "\n",
                                      encoding="utf-8")
    (folder / "model.config").write_text(
        '<?xml version="1.0"?>\n<model>\n  <name>{}</name>\n  <version>1.0</version>\n  <sdf version="1.9">model.sdf'
        '</sdf>\n  <description>Generated by course/gazebo/make_sim_drone.py from PX4 {} (propeller collisions '
        'removed).</description>\n</model>\n'.format(name, source), encoding="utf-8")


def _retarget(root: ET.Element, old: str, new: str, name: str) -> ET.Element:
    model = root.find("model")
    model.set("name", name)
    for uri in model.iter("uri"):
        if uri.text and uri.text.strip() in (old, "model://" + old):
            uri.text = "model://" + new
    return root


def make(px4: Path, out: Path) -> list:
    models = px4 / "Tools" / "simulation" / "gz" / "models"
    base = ET.parse(models / "x500_base" / "model.sdf").getroot()
    model = base.find("model")
    model.set("name", "x500_course_base")
    removed = 0
    for link in model.iter("link"):
        if link.get("name", "").startswith("rotor"):
            for c in list(link.findall("collision")):
                link.remove(c)
                removed += 1
    if removed == 0:
        raise RuntimeError("no rotor collisions found in {}; PX4's x500 model changed?".format(models / "x500_base"))
    _write(out / "x500_course_base", "x500_course_base", base, "x500_base")
    _write(out / "x500_course", "x500_course",
           _retarget(ET.parse(models / "x500" / "model.sdf").getroot(), "x500_base", "x500_course_base", "x500_course"),
           "x500")
    written = ["x500_course_base", "x500_course"]
    lidar = models / "x500_lidar_2d" / "model.sdf"
    if lidar.is_file():
        _write(out / "x500_course_lidar_2d", "x500_course_lidar_2d",
               _retarget(ET.parse(lidar).getroot(), "x500", "x500_course", "x500_course_lidar_2d"), "x500_lidar_2d")
        written.append("x500_course_lidar_2d")
    return written


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--px4", type=Path, default=Path.home() / "PX4-Autopilot", help="PX4-Autopilot checkout")
    ap.add_argument("--out", type=Path, default=HERE / "models", help="models folder")
    args = ap.parse_args(argv)
    try:
        written = make(args.px4, args.out)
    except (OSError, RuntimeError, ET.ParseError) as exc:
        print("could not make the sim drone: {}".format(exc), file=sys.stderr)
        return 2
    print("wrote {} into {}".format(", ".join(written), args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
